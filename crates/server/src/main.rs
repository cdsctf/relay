use cds_relay_native::ServerIdentity;
use cds_relay_server::{Config, identity, native::NativeServer};
use clap::{Parser, Subcommand};
use std::{io, net::SocketAddr, path::PathBuf, time::Duration};
use tokio_util::sync::CancellationToken;

#[derive(Parser)]
#[command(
    version,
    about = "CdsCTF authenticated native TCP/UDP relay",
    subcommand_negates_reqs = true,
    args_conflicts_with_subcommands = true
)]
struct Args {
    #[command(subcommand)]
    command: Option<Command>,
    /// TCP and UDP listening address; both protocols use the same numerical port.
    #[arg(long, default_value = "127.0.0.1:9527")]
    listen: SocketAddr,
    /// Secret relay identity JSON generated by the init command.
    #[arg(long, required = true)]
    identity: Option<PathBuf>,
    #[arg(long, default_value_t = 256)]
    max_connections: usize,
    #[arg(long, default_value_t = 5)]
    handshake_timeout: u64,
    #[arg(long, default_value_t = 5)]
    connect_timeout: u64,
    #[arg(long, default_value_t = 60)]
    udp_idle_timeout: u64,
    /// Aggregate TCP payload Mbps per direction across every connection (0 disables).
    #[arg(long, default_value_t = 0, value_parser = clap::value_parser!(u64).range(0..=8_000_000))]
    tcp_rate_limit_mbps: u64,
    /// Drop expired packets in relay receive-dispatch queues (0 disables).
    #[arg(long, default_value_t = 0, value_parser = clap::value_parser!(u64).range(0..=1000))]
    udp_max_queue_delay_ms: u64,
}

#[derive(Subcommand)]
enum Command {
    /// Generate mutual TLS identities into a new private directory.
    Init {
        #[arg(long, default_value = "relay-identity")]
        out: PathBuf,
        /// Relay address reachable from the platform; independent of the listen address.
        #[arg(long)]
        endpoint: SocketAddr,
        /// DNS name or IP included in the relay certificate and verified by the platform.
        #[arg(long, default_value = "cds-relay")]
        server_name: String,
    },
}

fn main() -> io::Result<()> {
    let args = Args::parse();
    if let Some(Command::Init {
        out,
        endpoint,
        server_name,
    }) = args.command
    {
        identity::initialize(&out, endpoint, server_name)?;
        println!("Created server.json and platform.json in {}", out.display());
        return Ok(());
    }
    run(args)
}

#[tokio::main]
async fn run(args: Args) -> io::Result<()> {
    tracing_subscriber::fmt()
        .with_env_filter(
            tracing_subscriber::EnvFilter::try_from_default_env().unwrap_or_else(|_| "info".into()),
        )
        .init();
    let config = Config {
        max_connections: args.max_connections,
        tcp_rate_limit: (args.tcp_rate_limit_mbps != 0)
            .then_some(args.tcp_rate_limit_mbps * 125_000),
        handshake_timeout: Duration::from_secs(args.handshake_timeout),
        connect_timeout: Duration::from_secs(args.connect_timeout),
        udp_idle_timeout: Duration::from_secs(args.udp_idle_timeout),
        udp_max_queue_delay: (args.udp_max_queue_delay_ms != 0)
            .then_some(Duration::from_millis(args.udp_max_queue_delay_ms)),
    };
    config.validate()?;
    let shutdown = CancellationToken::new();
    let signals = async {
        #[cfg(unix)]
        {
            let mut terminate =
                tokio::signal::unix::signal(tokio::signal::unix::SignalKind::terminate())?;
            tokio::select! { result = tokio::signal::ctrl_c() => result?, _ = terminate.recv() => {} }
        }
        #[cfg(not(unix))]
        tokio::signal::ctrl_c().await?;
        Ok::<_, io::Error>(())
    };
    let identity = ServerIdentity::read(args.identity.as_ref().unwrap())?;
    let endpoint = NativeServer::bind(args.listen, &identity, config).await?;
    tracing::info!(address = %endpoint.local_addr()?, "relay TCP + UDP listener ready (mTLS + DTLS)");
    let server = endpoint.serve(shutdown.clone());
    tokio::pin!(server);
    tokio::select! {
        result = &mut server => result,
        signal = signals => {
            shutdown.cancel();
            let result = server.await;
            signal.and(result)
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn serving_requires_identity_but_initialization_does_not() {
        assert!(Args::try_parse_from(["cds-relay-server"]).is_err());
        assert!(Args::try_parse_from(["cds-relay-server", "--listen", "0.0.0.0:9527"]).is_err());
        assert!(Args::try_parse_from(["cds-relay-server", "--identity", "server.json"]).is_ok());
        let args =
            Args::try_parse_from(["cds-relay-server", "init", "--endpoint", "127.0.0.1:9527"])
                .unwrap();
        assert!(matches!(args.command, Some(Command::Init { .. })));
    }

    #[test]
    fn removed_transport_and_experimental_flags_are_rejected() {
        for obsolete in [
            vec!["--transport", "stream"],
            vec!["--transport", "quic"],
            vec!["--check"],
            vec!["--backend", "quic"],
            vec!["--backend", "native"],
            vec!["--congestion-control", "bbr"],
        ] {
            let mut args = vec!["cds-relay-server", "--identity", "server.json"];
            args.extend(obsolete);
            let Err(error) = Args::try_parse_from(args) else {
                panic!("removed option accepted");
            };
            assert_eq!(error.kind(), clap::error::ErrorKind::UnknownArgument);
        }
    }
}
